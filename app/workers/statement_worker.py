def parse_optional_date(value: str | None, field: str) -> date | None:
    if value is None:
        return None
    try:
        return date.fromisoformat(value)
    except ValueError as error:
        raise ValueError(f"Statement {field} must be an ISO date") from error


def process_job(job: dict[str, Any], table=None, s3=None) -> dict[str, str]:
    account_id = job.get("account_id")
    job_id = job.get("job_id")
    if not isinstance(account_id, str) or not account_id:
        raise ValueError("Statement job must include account_id")
    if not isinstance(job_id, str) or not job_id:
        raise ValueError("Statement job must include job_id")
    start_date = parse_optional_date(job.get("start_date"), "start_date")
    end_date = parse_optional_date(job.get("end_date"), "end_date")
    if start_date and end_date and end_date < start_date:
        raise ValueError("Statement end_date must be on or after start_date")
    bucket = BUCKET_NAME
    if not bucket:
        raise RuntimeError("KYC_STATEMENTS_BUCKET must be configured")

    table = table or dynamodb_resource().Table(TABLE_NAME)
    s3 = s3 or s3_client()
    transactions = load_transactions(table, account_id)
    transactions = [
        item for item in transactions if in_date_range(item, start_date, end_date)
    ]
    content = statement_html(job, transactions).encode("utf-8")
    object_key = f"statements/{account_id}/{job_id}.html"

    s3.put_object(
        Bucket=bucket,
        Key=object_key,
        Body=content,
        ContentType="text/html; charset=utf-8",
        ServerSideEncryption="aws:kms",
    )
    download_url = s3.generate_presigned_url(
        "get_object",
        Params={"Bucket": bucket, "Key": object_key},
        ExpiresIn=PRESIGNED_URL_EXPIRATION,
    )
    completed_at = datetime.now(timezone.utc).isoformat()
    table.put_item(
        Item={
            "PK": f"STATEMENT#{job_id}",
            "SK": "JOB",
            "record_type": "STATEMENT_JOB",
            "job_id": job_id,
            "account_id": account_id,
            "status": "COMPLETED",
            "object_key": object_key,
            "download_url": download_url,
            "url_expires_at": int(time.time()) + PRESIGNED_URL_EXPIRATION,
            "completed_at": completed_at,
        }
    )
    return {"job_id": job_id, "object_key": object_key, "download_url": download_url}


def process_message(message: dict[str, Any], table=None, s3=None) -> None:
    job = json.loads(message["Body"])
    if not isinstance(job, dict):
        raise ValueError("Statement queue message must be a JSON object")
    result = process_job(job, table=table, s3=s3)
    logger.info("Statement job completed job_id=%s object_key=%s", result["job_id"], result["object_key"])


def run() -> None:
    if not QUEUE_URL:
        raise RuntimeError("STATEMENT_QUEUE_URL must be configured")
    if not BUCKET_NAME:
        raise RuntimeError("KYC_STATEMENTS_BUCKET must be configured")

    sqs = sqs_client()
    table = dynamodb_resource().Table(TABLE_NAME)
    s3 = s3_client()
    while running:
        response = sqs.receive_message(
            QueueUrl=QUEUE_URL,
            MaxNumberOfMessages=1,
            WaitTimeSeconds=20,
            VisibilityTimeout=300,
        )
        for message in response.get("Messages", []):
            try:
                process_message(message, table=table, s3=s3)
                sqs.delete_message(
                    QueueUrl=QUEUE_URL,
                    ReceiptHandle=message["ReceiptHandle"],
                )
            except Exception:
                logger.exception("Statement job failed message_id=%s", message.get("MessageId", "unknown"))


if __name__ == "__main__":
    signal.signal(signal.SIGINT, _stop)
    signal.signal(signal.SIGTERM, _stop)
    run()
